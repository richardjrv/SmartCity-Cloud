-- Historial de reportes y de cada actualización de estado.
-- FastAPI escribe mediante DATABASE_URL; no se concede acceso directo al navegador.

create table if not exists public.alerta_historial (
    id bigint generated by default as identity primary key,
    alerta_id bigint not null references public.alertas(id) on delete cascade,
    actor_id integer references public.usuarios(id) on delete set null,
    estado_anterior text check (
        estado_anterior is null or estado_anterior in ('pendiente', 'en_proceso', 'resuelto')
    ),
    estado_nuevo text not null check (estado_nuevo in ('pendiente', 'en_proceso', 'resuelto')),
    observacion text check (observacion is null or char_length(observacion) <= 280),
    creado_en timestamptz not null default now()
);

create index if not exists alerta_historial_alerta_fecha_idx
    on public.alerta_historial (alerta_id, creado_en, id);

alter table public.alerta_historial enable row level security;
revoke all on table public.alerta_historial from public, anon, authenticated;
revoke all on sequence public.alerta_historial_id_seq from public, anon, authenticated;

comment on table public.alerta_historial is
    'Trazabilidad de reportes, cambios de estado y observaciones administrativas.';
