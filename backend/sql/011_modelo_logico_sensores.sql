-- Extiende el catálogo IoT al modelo lógico de sensores, magnitudes, lecturas y comandos.
-- dispositivos_iot conserva los códigos de controlador usados por el firmware actual.

begin;

create or replace view public.controladores
with (security_invoker = true)
as
select sensor_id as id_controlador,
       nombre,
       firmware_version as modelo,
       ubicacion,
       observaciones as descripcion,
       intervalo_esperado_segundos,
       activo as estado
from public.dispositivos_iot;

create table if not exists public.magnitudes (
    id_magnitud integer generated by default as identity primary key,
    codigo text not null unique check (btrim(codigo) <> ''),
    nombre text not null,
    descripcion text,
    unidad text not null default ''
);

insert into public.magnitudes (codigo, nombre, descripcion, unidad) values
    ('temperatura', 'Temperatura', 'Temperatura ambiente reportada por el sensor.', '°C'),
    ('humedad', 'Humedad relativa', 'Humedad relativa del ambiente.', '%'),
    ('calidad_aire', 'Calidad del aire', 'Lectura de calidad del aire; requiere conocer la calibración.', 'lectura'),
    ('distancia_cm', 'Distancia', 'Distancia medida por ultrasonido.', 'cm'),
    ('lluvia_detectada', 'Lluvia detectada', 'Estado digital de detección de lluvia.', 'estado'),
    ('luminosidad', 'Luminosidad', 'Lectura de LDR; la unidad depende de la calibración.', 'lectura'),
    ('nivel_agua', 'Nivel de agua', 'Lectura de nivel de agua; la unidad depende de la calibración.', 'lectura'),
    ('reflectancia_tcrt5000', 'Reflectancia TCRT5000', 'Lectura analógica del sensor de reflectancia.', 'lectura'),
    ('tcrt5000_detectado', 'Proximidad detectada', 'Estado digital del TCRT5000.', 'estado')
on conflict (codigo) do update
set nombre = excluded.nombre,
    descripcion = excluded.descripcion,
    unidad = excluded.unidad;

create table if not exists public.sensores (
    id_sensor bigint generated by default as identity primary key,
    codigo text not null unique check (btrim(codigo) <> ''),
    id_controlador varchar not null references public.dispositivos_iot(sensor_id) on update cascade on delete restrict,
    nombre text not null,
    modelo text,
    ubicacion text,
    estado text not null default 'pendiente' check (estado in ('activo', 'inactivo', 'pendiente')),
    objeto_modelo text,
    observaciones text,
    creado_en timestamptz not null default now(),
    actualizado_en timestamptz not null default now(),
    constraint sensores_objeto_modelo_no_vacio check (objeto_modelo is null or btrim(objeto_modelo) <> '')
);

create index if not exists idx_sensores_controlador on public.sensores (id_controlador);
create unique index if not exists idx_sensores_objeto_modelo on public.sensores (objeto_modelo) where objeto_modelo is not null;

create table if not exists public.sensor_magnitud (
    id_sensor bigint not null references public.sensores(id_sensor) on delete cascade,
    id_magnitud integer not null references public.magnitudes(id_magnitud) on delete restrict,
    primary key (id_sensor, id_magnitud)
);

create table if not exists public.lecturas (
    id_lectura bigint generated by default as identity primary key,
    id_sensor bigint not null,
    id_magnitud integer not null,
    fecha_hora timestamptz not null,
    valor numeric(14, 4),
    valor_booleano boolean,
    origen text not null default 'esp32' check (origen in ('esp32', 'manual', 'simulacion')),
    constraint lecturas_valor_unico check (num_nonnulls(valor, valor_booleano) = 1),
    constraint lecturas_sensor_magnitud_fk foreign key (id_sensor, id_magnitud)
        references public.sensor_magnitud(id_sensor, id_magnitud) on delete restrict
);

create index if not exists idx_lecturas_sensor_magnitud_fecha
    on public.lecturas (id_sensor, id_magnitud, fecha_hora desc);

create table if not exists public.comandos (
    id_comando bigint generated by default as identity primary key,
    id_actuador bigint not null references public.actuadores(id) on delete restrict,
    fecha_solicitud timestamptz not null default now(),
    accion text not null check (accion in ('encender', 'apagar', 'automatico')),
    valor boolean,
    origen text not null default 'panel' check (origen in ('panel', 'automatizacion', 'sistema')),
    estado_ejecucion text not null default 'pendiente'
        check (estado_ejecucion in ('pendiente', 'enviado', 'ejecutado', 'fallido', 'cancelado')),
    fecha_ejecucion timestamptz,
    observaciones text,
    solicitado_por integer references public.usuarios(id) on delete set null,
    constraint comandos_valor_accion check (
        (accion = 'encender' and valor is true)
        or (accion = 'apagar' and valor is false)
        or (accion = 'automatico' and valor is null)
    )
);

create index if not exists idx_comandos_actuador_solicitud
    on public.comandos (id_actuador, fecha_solicitud desc);
create index if not exists idx_comandos_pendientes
    on public.comandos (estado_ejecucion, fecha_solicitud)
    where estado_ejecucion in ('pendiente', 'enviado');

comment on view public.controladores is
    'Vista de compatibilidad: presenta dispositivos_iot con el nombre Controlador del modelo lógico.';
comment on table public.sensores is
    'Inventario de sensores físicos. El objeto_modelo se completa solo cuando la ubicación real en el GLB se conoce.';
comment on table public.sensor_magnitud is
    'Relación de las magnitudes que mide cada sensor físico.';
comment on table public.lecturas is
    'Lecturas normalizadas por sensor y magnitud; la tabla lecturas_sensores conserva compatibilidad con firmware actual.';
comment on table public.comandos is
    'Historial de comandos. Pendiente significa que el actuador aún no confirmó su ejecución física.';

alter table public.magnitudes enable row level security;
alter table public.sensores enable row level security;
alter table public.sensor_magnitud enable row level security;
alter table public.lecturas enable row level security;
alter table public.comandos enable row level security;

revoke all on table public.controladores, public.magnitudes, public.sensores,
    public.sensor_magnitud, public.lecturas, public.comandos
    from public, anon, authenticated;

commit;
