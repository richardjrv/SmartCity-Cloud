-- Alertas que cualquier usuario autenticado puede reportar y el administrador gestiona.
-- La API FastAPI accede a PostgreSQL; no se habilita acceso directo desde el navegador.

create table if not exists public.alertas (
    id bigint generated by default as identity primary key,
    origen text not null check (origen in ('usuario', 'sensor')),
    titulo text not null check (char_length(btrim(titulo)) between 3 and 120),
    descripcion text not null check (char_length(btrim(descripcion)) between 3 and 1500),
    sensor_id text,
    metrica text,
    estado text not null default 'pendiente'
        check (estado in ('pendiente', 'en_proceso', 'resuelto')),
    creado_por integer references public.usuarios(id) on delete set null,
    actualizado_por integer references public.usuarios(id) on delete set null,
    creado_en timestamptz not null default now(),
    actualizado_en timestamptz not null default now(),
    constraint alertas_sensor_campos check (
        (origen = 'sensor' and sensor_id is not null and metrica is not null)
        or origen = 'usuario'
    )
);

-- Una alerta activa persistente por variable del único ESP32.
create unique index if not exists alertas_sensor_metrica_uq
    on public.alertas (sensor_id, metrica)
    where origen = 'sensor';
create index if not exists alertas_creado_en_desc_idx
    on public.alertas (creado_en desc);
create index if not exists alertas_estado_idx
    on public.alertas (estado);

alter table public.alertas enable row level security;
revoke all on table public.alertas from public, anon, authenticated;
revoke all on sequence public.alertas_id_seq from public, anon, authenticated;

comment on table public.alertas is
    'Avisos reportados por usuarios y alertas de sensores; los cambios de estado se validan en FastAPI.';
